# -*- coding: utf-8 -*-
"""Produces paper/fig_gantt.tex: the anatomy of one solution of the niche problem
(Figure 1, §2.1).

The instance is generated by `niche_generator` at PRODUCTION PARAMETERS (n=10, m=3,
tau=1-99, rho=0.2, seed=20). The schedule is provably optimal by FULL ENUMERATION: all
3^10 assignments are scanned, and each machine's open-path ATSP is solved exactly with
Held-Karp. The spans are additionally compared against the SHARED checker's own
computation (`feasibility.sequence_makespan`).

seed=20 was chosen for READABILITY (all three features stand out): M3 is ready at t=2
but stays idle, because J3 is eligible only on M1, and J2 and J4 only on M2. This is a
FIGURE, not a comparison result, so choosing the seed is legitimate.

Usage: python3 gen_gantt.py    ->  paper/fig_gantt.tex
"""
import itertools

from niche_generator import gen_instance
from feasibility import sequence_makespan

N, M, TAU, RHO, SEED = 10, 3, 99, 0.2, "20"
OUT = "paper/fig_gantt.tex"

XS, ROW, H = 0.0525, 0.90, 0.46        # cm per time unit, row spacing, bar height


def best_path(jobs, p, s, r):
    """Open path, EXACT solution (Held-Karp). -> (span, sequence)"""
    if not jobs:
        return 0, ()
    k = len(jobs)
    INF = float("inf")
    dp = [[INF] * k for _ in range(1 << k)]
    par = [[-1] * k for _ in range(1 << k)]
    for t, j in enumerate(jobs):
        dp[1 << t][t] = p[j]                                  # the first job pays no setup
    for mask in range(1 << k):
        for last in range(k):
            if dp[mask][last] == INF:
                continue
            for nxt in range(k):
                if mask >> nxt & 1:
                    continue
                v = dp[mask][last] + s[jobs[last]][jobs[nxt]] + p[jobs[nxt]]
                nm = mask | (1 << nxt)
                if v < dp[nm][nxt]:
                    dp[nm][nxt], par[nm][nxt] = v, last
    full = (1 << k) - 1
    lo = min(range(k), key=lambda t: dp[full][t])
    seq, mask, last = [], full, lo
    while last != -1:
        seq.append(jobs[last])
        pl = par[mask][last]
        mask ^= (1 << last)
        last = pl
    return r + dp[full][lo], tuple(reversed(seq))


def solve(d):
    """Full enumeration: 3^n assignments x Held-Karp per machine. -> (makespan, [(span, seq)])"""
    n, m = d["nJob"], d["nMachine"]
    P = {l: d["processTime"][str(l)] for l in range(m)}
    S = {l: d["setupTime"][str(l)] for l in range(m)}
    R = {l: d["readyTime"][str(l)] for l in range(m)}
    C = {l: d["Compatibility"][str(l)] for l in range(m)}
    elig = [[l for l in range(m) if C[l][i] == 1] for i in range(n)]
    cache = {}

    def span(l, subset):
        if (l, subset) not in cache:
            cache[l, subset] = best_path(subset, P[l], S[l], R[l])
        return cache[l, subset]

    best = (float("inf"), None)
    for assign in itertools.product(*elig):
        buckets = tuple(tuple(i for i in range(n) if assign[i] == l) for l in range(m))
        mk, ok = 0, True
        for l in range(m):
            sp, _ = span(l, buckets[l])
            if sp >= best[0]:
                ok = False
                break
            mk = max(mk, sp)
        if ok and mk < best[0]:
            best = (mk, buckets)
    mk, buckets = best
    return mk, [span(l, buckets[l]) for l in range(m)], elig


def main():
    d = gen_instance(N, M, TAU, RHO, SEED)
    mk, spans, elig = solve(d)
    P = {l: d["processTime"][str(l)] for l in range(M)}
    S = {l: d["setupTime"][str(l)] for l in range(M)}
    R = {l: d["readyTime"][str(l)] for l in range(M)}

    # --- CROSS-CHECK WITH THE SHARED CHECKER ---
    for l in range(M):
        seq = list(spans[l][1])
        assert abs(sequence_makespan(seq, l, R, P, S) - spans[l][0]) < 1e-9, \
            f"span uyusmuyor: makine {l}"
        for i in seq:
            assert l in elig[i], f"uygunluk ihlali: is {i} makine {l}"
    assert sorted(i for _, sq in spans for i in sq) == list(range(N)), "kapsama ihlali"

    o, w = [], None
    o.append(r"%% OTOMATIK URETILDI == gen_gantt.py.  niche_generator seed=%s, n=%d, m=%d,"
             % (SEED, N, M))
    o.append(r"%% tau=1-%d, rho=%s.  Cizelge TAM SAYIMLA kanitli optimal (Cmax=%d); span'lar"
             % (TAU, RHO, mk))
    o.append(r"% feasibility.sequence_makespan ile capraz kontrol edildi, ihlal 0.")
    o.append(r"% Yatayda TEK referans sistemi var (zaman): sag C_l sutunu bu yuzden YOK,")
    o.append(r"% sayilar basliktan okunuyor (kullanici 2026-08-23).")
    w = o.append
    w(r"\begin{figure}[!htbp]\centering")
    w(r"\footnotesize")
    w(r"\begin{tikzpicture}[x=%.4fcm, y=1cm," % XS)
    w(r"  proc/.style = {draw=black, line width=0.4pt, fill=black!10},")
    w(r"  setp/.style = {draw=black, line width=0.4pt, fill=black!48},")
    w(r"  redy/.style = {draw=black, line width=0.4pt, fill=white,")
    w(r"                 pattern=north east lines, pattern color=black!55},")
    w(r"  jl/.style   = {font=\scriptsize, inner sep=0pt},")
    w(r"  ax/.style   = {draw=black!55, line width=0.4pt}]")
    w("")
    ymax = (M - 1) * ROW + H / 2 + 0.28
    for l in range(M):
        y = (M - 1 - l) * ROW
        sp, seq = spans[l]
        w(r"%% ==== makine M%d (span %d) ====" % (l + 1, sp))
        w(r"\node[jl, anchor=east] at (-6, %.3f) {$M_%d$};" % (y, l + 1))
        t = 0
        if R[l] > 0:
            w(r"\draw[redy] (%d,%.3f) rectangle (%d,%.3f);" % (t, y - H/2, R[l], y + H/2))
            t = R[l]
        for k, j in enumerate(seq):
            if k:
                st = S[l][seq[k-1]][j]
                w(r"\draw[setp] (%d,%.3f) rectangle (%d,%.3f);" % (t, y - H/2, t + st, y + H/2))
                t += st
            p = P[l][j]
            w(r"\draw[proc] (%d,%.3f) rectangle (%d,%.3f);" % (t, y - H/2, t + p, y + H/2))
            if p >= 14:
                w(r"\node[jl] at (%.1f,%.3f) {$J_{%d}$};" % (t + p/2, y, j))
            else:                                    # narrow block: label BELOW the bar
                w(r"\node[jl, anchor=north, inner sep=1.5pt] at (%.1f,%.3f) {$J_{%d}$};"
                  % (t + p/2, y - H/2, j))
            t += p
        assert t == sp
        w("")
    w(r"%% ==== zaman ekseni (yataydaki TEK referans sistemi) ====")
    ybase = -H/2 - 0.30
    w(r"\draw[ax, ->, >={Stealth[length=1.6mm]}] (0,%.3f) -- (213,%.3f);" % (ybase, ybase))
    for tk in range(0, 201, 50):
        w(r"\draw[ax] (%d,%.3f) -- (%d,%.3f) node[jl, anchor=north, inner sep=2pt] {%d};"
          % (tk, ybase, tk, ybase - 0.07, tk))
    w(r"\node[jl, anchor=west] at (217,%.3f) {time};" % ybase)
    w(r"\draw[dashed, line width=0.6pt] (%d,%.3f) -- (%d,%.3f)" % (mk, ybase, mk, ymax))
    w(r"   node[jl, anchor=south] {$C_{\max}=%d$};" % mk)
    sp3 = spans[2][0]
    w(r"\draw[densely dotted, draw=black!55, line width=0.4pt] (%d,%.3f) rectangle (%d,%.3f);"
      % (sp3, -H/2, mk, H/2))
    w(r"\node[jl, text=black!60] at (%.1f,0) {idle};" % ((sp3 + mk) / 2))
    ly = ymax + 0.46
    w(r"%% ==== aciklama seridi ====")
    for x0, lab in ((0, r"machine ready time $r_\ell$"), (86, r"processing $p_{i\ell}$"),
                    (150, r"setup $s_{ij\ell}$")):
        sty = "redy" if x0 == 0 else ("proc" if x0 == 86 else "setp")
        w(r"\draw[%s] (%d,%.3f) rectangle (%d,%.3f);" % (sty, x0, ly - 0.13, x0 + 16, ly + 0.13))
        w(r"\node[jl, anchor=west] at (%d,%.3f) {%s};" % (x0 + 20, ly, lab))
    w(r"\end{tikzpicture}")
    w(r"\caption{An optimal schedule for a ten-job, three-machine instance of")
    w(r"$R \mid s_{ij\ell}, M_j, r_\ell \mid C_{\max}$, drawn to scale. Each machine")
    w(r"starts at its own ready time, and a setup separates every pair of consecutive")
    w(r"jobs. Machine $M_3$ is free from $t=2$ yet finishes $62$ units before the")
    w(r"makespan. Eligibility is what keeps it idle: $J_3$ may run only on $M_1$, and")
    w(r"$J_2$ and $J_4$ only on $M_2$. The makespan is set by $M_2$, with $M_1$ four")
    w(r"units behind it.}\label{fig:gantt}")
    w(r"\end{figure}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print(f"{OUT} yazildi | Cmax={mk} | span={[s for s, _ in spans]} | denetim OK")


if __name__ == "__main__":
    main()
